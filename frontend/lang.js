function changeSiteLanguage(lang) {
  if (!translations[lang]) lang = 'en'; // unknown stored value → fall back, never throw
  localStorage.setItem('bt_lang', lang);
  document.documentElement.lang = lang; // screen readers pick the right voice

  // Set active state on lang toggles (if they exist)
  document.querySelectorAll('.lang-toggle').forEach(el => {
    const active = el.dataset.lang === lang;
    el.classList.toggle('active', active);
    el.setAttribute('aria-pressed', active ? 'true' : 'false');
  });

  const dict = translations[lang];

  // Static, trusted dictionary strings only (some contain markup such as
  // <span class='grad-text'>). Elements showing live state must NOT carry
  // data-i18n — pages re-render those from their own state instead.
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Let pages re-run anything that depends on the rewritten text.
  document.dispatchEvent(new CustomEvent('bt:langchange', { detail: { lang } }));
}

/** Saved choice, else the browser's language (Turkish browsers get Turkish). */
function preferredLanguage() {
  const saved = localStorage.getItem('bt_lang');
  if (translations[saved]) return saved;
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
  return /^tr\b/i.test(nav) ? 'tr' : 'en';
}

// Initialization on load
document.addEventListener('DOMContentLoaded', () => {
  changeSiteLanguage(preferredLanguage());
});
